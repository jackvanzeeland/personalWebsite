/**
 * Generates infrastructure/spa-router-function.js — the CloudFront Function
 * on the default behavior: 301s legacy URLs (same map the client router uses),
 * 301s trailing slashes to the canonical URL, and serves each path's
 * prerendered /<path>/index.html (unknown paths fall through to a real 404).
 * Also rewrites the same code into infrastructure.yaml's UrlRewriteFunction.
 * Run automatically as part of `npm run build`.
 */

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { LEGACY_MAP } from '../src/app/legacyRedirects.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'infrastructure', 'spa-router-function.js');

const fn = `// AUTO-GENERATED by scripts/generate-redirects.mjs — do not edit.
// CloudFront Function (cloudfront-js-2.0): legacy 301s, canonical URLs, and
// routing to the prerendered pages (scripts/prerender.ts).

var LEGACY_MAP = ${JSON.stringify(LEGACY_MAP, null, 2)};

function redirect(location) {
  return {
    statusCode: 301,
    statusDescription: 'Moved Permanently',
    headers: { location: { value: location } }
  };
}

function querystring(request) {
  var q = request.querystring || {};
  var parts = [];
  for (var key in q) {
    var entry = q[key];
    var values = entry.multiValue ? entry.multiValue : [entry];
    for (var i = 0; i < values.length; i++) {
      parts.push(values[i].value ? key + '=' + values[i].value : key);
    }
  }
  return parts.length ? '?' + parts.join('&') : '';
}

// CloudFront invokes handler() by name; there is no in-file caller.
// eslint-disable-next-line no-unused-vars
function handler(event) {
  var request = event.request;
  var uri = request.uri;

  // Normalize: strip .html and trailing slash (except root)
  var normalized = uri.replace(/\\.html$/, '');
  if (normalized.length > 1 && normalized.endsWith('/')) {
    normalized = normalized.slice(0, -1);
  }

  var target = LEGACY_MAP[normalized];
  if (target) {
    return redirect(target);
  }

  // Static assets pass through untouched
  if (uri.includes('.')) {
    return request;
  }

  // One URL per page: /projects/ → /projects (matches the canonical tag)
  if (normalized !== uri) {
    return redirect(normalized + querystring(request));
  }

  // Each page is a prerendered file: /projects/x → /projects/x/index.html.
  // Unknown paths have no such object, so S3 answers 403 and the
  // distribution's CustomErrorResponses serve 404.html with a real 404.
  request.uri = uri === '/' ? '/index.html' : uri + '/index.html';
  return request;
}
`;

await fs.mkdir(path.dirname(OUT), { recursive: true });
await fs.writeFile(OUT, fn);

// Keep the copy embedded in infrastructure.yaml identical (never hand-edit it):
// replace the indented FunctionCode block of the UrlRewriteFunction resource.
const YAML = path.join(ROOT, 'infrastructure.yaml');
const yaml = await fs.readFile(YAML, 'utf8');
const lines = yaml.split('\n');
const resource = lines.findIndex((l) => /^ {2}UrlRewriteFunction:\s*$/.test(l));
const codeLine = lines.findIndex((l, i) => i > resource && /^ {6}FunctionCode: \|\s*$/.test(l));
if (resource < 0 || codeLine < 0) throw new Error('generate-redirects: UrlRewriteFunction FunctionCode not found in infrastructure.yaml');
let end = codeLine + 1;
while (end < lines.length && (lines[end].startsWith('        ') || lines[end].trim() === '')) end++;
// Leave the blank line(s) separating it from the next resource in place
while (end > codeLine + 1 && lines[end - 1].trim() === '') end--;
const body = fn
  .trimEnd()
  .split('\n')
  .map((l) => (l ? `        ${l}` : ''));
lines.splice(codeLine + 1, end - codeLine - 1, ...body);
await fs.writeFile(YAML, lines.join('\n'));
console.log(`generate-redirects: ${Object.keys(LEGACY_MAP).length} legacy routes → ${path.relative(ROOT, OUT)}`);
